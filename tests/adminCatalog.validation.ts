import assert from 'node:assert/strict';
import { planProductImport, importRequestSchema } from '../src/utils/productImport';
import { inventoryStatus } from '../src/utils/inventory';

const values = { name: 'Ignition Coil', brand: 'Test', category: 'Parts', description: 'A replacement coil for the specified motorcycle model.', price: '650', stock: '0', sku: '' };
const categories = [{ value: 'PARTS', label: 'Parts' }];
const planned = planProductImport([{ row: 2, values }], categories, []);
assert.equal(planned.valid, true);
assert.equal(planned.plans[0].product.isActive, false);
assert.equal(planned.plans[0].product.stock, 0);
assert.match(planned.plans[0].product.sku, /^BB-TEST-/);
const existing = [{ id: 'existing', sku: 'EXISTING', updatedAt: new Date(), isActive: true, discountPrice: 600, variants: [] }];
const update = planProductImport([{ row: 2, values: { ...values, sku: 'EXISTING' } }], categories, existing);
assert.equal(update.plans[0].action, 'update');
assert.equal(update.plans[0].product.discountPrice, undefined);
assert.equal(update.plans[0].product.isActive, undefined);
assert.equal(planProductImport([{ row: 2, values: { ...values, sku: 'EXISTING', price: '500' } }], categories, existing).valid, false);
assert.equal(planProductImport([{ row: 2, values: { ...values, sku: 'EXISTING', price: '500', discountPrice: 'CLEAR' } }], categories, existing).valid, true);
assert.equal(planProductImport([{ row: 2, values: { ...values, category: 'unknown' } }], categories, []).valid, false);
assert.equal(planProductImport([{ row: 2, values: { ...values, price: '-1' } }], categories, []).valid, false);
assert.equal(planProductImport([{ row: 2, values: { ...values, sku: 'EXISTING' } }, { row: 3, values: { ...values, sku: 'EXISTING' } }], categories, existing).valid, false);
assert.equal(planProductImport([{ row: 2, values: { ...values, sku: 'EXISTING' } }], categories, [{ ...existing[0], variants: [{}] }]).valid, false);
assert.equal(planProductImport([{ row: 2, values: { ...values, price: '0.001' } }], categories, []).valid, false);
assert.equal(importRequestSchema.safeParse({ rows: [] }).success, false);
assert.equal(inventoryStatus({ stock: 20, lowStockThreshold: 5, variants: [{ stock: 20, size: 'M', color: 'Black' }, { stock: 0, size: 'L', color: 'Black' }] }).inventoryStatus, 'low');
assert.equal(inventoryStatus({ stock: 20, lowStockThreshold: 0, variants: [{ stock: 0, size: 'L', color: 'Black' }] }).inventoryStatus, 'out');
assert.equal(inventoryStatus({ stock: 6, lowStockThreshold: 5 }).inventoryStatus, 'ok');
assert.equal(inventoryStatus({ stock: 5, lowStockThreshold: 5 }).inventoryStatus, 'low');
console.log('Import planning and variant-aware stock checks passed.');
